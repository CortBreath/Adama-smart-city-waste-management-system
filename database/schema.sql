-- ============================================================
-- VIEW: LATEST BIN STATUS
-- Used by the GIS map and bin dashboard
-- ============================================================

CREATE VIEW latest_bin_status AS

SELECT
    b.bin_id,

    ST_Y(b.geom::geometry) AS latitude,
    ST_X(b.geom::geometry) AS longitude,

    b.geom,
    b.status,
    b.data_source,
    b.last_seen_at,

    r.recorded_at,

    r.fill_level_pct,
    r.fill_distance,
    r.temperature,
    r.smoke_value,
    r.smoke_status,
    r.human_distance,
    r.lid_status,
    r.system_status

FROM bins b

LEFT JOIN LATERAL (
    SELECT *
    FROM bin_readings br
    WHERE br.bin_id = b.bin_id
    ORDER BY br.recorded_at DESC
    LIMIT 1
) r ON TRUE;


-- ============================================================
-- VIEW: LATEST DEVICE STATUS
-- ============================================================

CREATE VIEW latest_device_status AS

SELECT
    d.device_id,
    d.bin_id,

    ds.recorded_at,
    ds.online,
    ds.signal_strength,
    ds.battery_level,
    ds.firmware_version

FROM devices d

LEFT JOIN LATERAL (
    SELECT *
    FROM device_status
    WHERE device_status.device_id = d.device_id
    ORDER BY device_status.recorded_at DESC
    LIMIT 1
) ds ON TRUE;


-- ============================================================
-- VIEW: PENDING ALERTS
-- ============================================================

CREATE VIEW pending_alerts_view AS

SELECT
    a.id,
    a.bin_id,
    a.alert_type,
    a.severity,
    a.message,
    a.created_at,
    a.assigned_janitor_id

FROM alerts a

WHERE a.resolved_at IS NULL;

-- ============================================================
-- USERS
-- System users and administrators
-- ============================================================

CREATE TABLE IF NOT EXISTS users (
    id BIGSERIAL PRIMARY KEY,

    username VARCHAR(100) NOT NULL UNIQUE,

    password_hash TEXT NOT NULL,

    role VARCHAR(30) NOT NULL DEFAULT 'user',

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_users_role
        CHECK (role IN ('admin', 'user'))
);